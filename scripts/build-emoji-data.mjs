/**
 * Regenerate src/lib/emojiData.ts from the Unicode emoji keyboard list.
 *
 *   node scripts/build-emoji-data.mjs [path-to-emoji-test.txt]
 *
 * With no argument it fetches the current list from unicode.org. This is the
 * same set an iPhone keyboard offers — Apple just draws its own artwork for
 * these code points, so picking from here gives Apple emoji on Apple devices.
 *
 * Skin-tone variants are dropped: they are modifier sequences of the base
 * emoji and would multiply the list ~3x for the same pictures.
 */
import fs from "node:fs";
import path from "node:path";

const SOURCE = "https://unicode.org/Public/emoji/latest/emoji-test.txt";
const OUT = path.resolve("src/lib/emojiData.ts");

async function readSource() {
  const local = process.argv[2];
  if (local) return fs.readFileSync(local, "utf8");
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`fetch ${SOURCE} failed: ${res.status}`);
  return res.text();
}

function parse(text) {
  const groups = [];
  let current = null;
  let version = "unknown";
  for (const line of text.split("\n")) {
    const versionMatch = /^#\s*Version:\s*(.+)$/.exec(line);
    if (versionMatch) version = versionMatch[1].trim();
    const groupMatch = /^#\s*group:\s*(.+)$/.exec(line);
    if (groupMatch) {
      current = { name: groupMatch[1].trim(), emoji: [] };
      groups.push(current);
      continue;
    }
    if (line.startsWith("#") || !line.trim()) continue;
    if (!line.includes("; fully-qualified")) continue;
    const comment = line.split("#")[1];
    if (!comment || !current) continue;
    // "😀 E1.0 grinning face"
    const m = /^\s*(\S+)\s+E\d+(?:\.\d+)?\s+(.*)$/.exec(comment);
    if (!m) continue;
    const [, char, name] = m;
    if (name.includes("skin tone")) continue;
    // Lower-cased so the picker can match a lower-cased query directly
    // ("ZZZ" and "flag: United States" would otherwise never match).
    current.emoji.push({ char, name: name.trim().toLowerCase() });
  }
  return { version, groups: groups.filter((g) => g.emoji.length > 0) };
}

const { version, groups } = parse(await readSource());
const total = groups.reduce((n, g) => n + g.emoji.length, 0);

const body = groups
  .map((g) => {
    const rows = g.emoji
      .map((e) => `    [${JSON.stringify(e.char)}, ${JSON.stringify(e.name)}],`)
      .join("\n");
    return `  {\n    name: ${JSON.stringify(g.name)},\n    emoji: [\n${rows}\n    ],\n  },`;
  })
  .join("\n");

const file = `// Generated by scripts/build-emoji-data.mjs — do not edit by hand.
// Source: Unicode emoji-test.txt (Version: ${version}), ${total} emoji.
// These are the standard code points an iPhone keyboard offers; Apple devices
// draw them with Apple Color Emoji.

/** [character, searchable name] */
export type EmojiEntry = [string, string];

export interface EmojiGroup {
  name: string;
  emoji: EmojiEntry[];
}

export const EMOJI_GROUPS: EmojiGroup[] = [
${body}
];
`;

fs.writeFileSync(OUT, file);
console.log(`wrote ${OUT}: ${groups.length} groups, ${total} emoji (Unicode ${version})`);
